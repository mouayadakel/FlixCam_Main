#!/usr/bin/env node
/**
 * Appends keys from .env.example missing in .env (never overwrites existing keys).
 * Generates MARKETING_CAPI_ROUTE_SECRET when adding that key.
 * Writes .env.local with all NEXT_PUBLIC_* from resulting .env.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs'
import { randomBytes } from 'crypto'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const envPath = join(root, '.env')
const examplePath = join(root, '.env.example')
const localPath = join(root, '.env.local')

function parseKeys(content) {
  const keys = new Set()
  for (const line of content.split('\n')) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/)
    if (m) keys.add(m[1])
  }
  return keys
}

function extractKey(line) {
  const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/)
  return m ? m[1] : null
}

function envValue(content, key) {
  const re = new RegExp(`^\\s*${key}=(.*)$`, 'm')
  const m = content.match(re)
  if (!m) return ''
  return m[1].trim().replace(/^["']|["']$/g, '')
}

if (!existsSync(envPath) || !existsSync(examplePath)) {
  process.stderr.write('Missing .env or .env.example\n')
  process.exit(1)
}

let envContent = readFileSync(envPath, 'utf8')
const exampleContent = readFileSync(examplePath, 'utf8')
const existingKeys = parseKeys(envContent)

const linesToAdd = []
for (const line of exampleContent.split('\n')) {
  const key = extractKey(line)
  if (!key || existingKeys.has(key)) continue
  let out = line
  if (key === 'MARKETING_CAPI_ROUTE_SECRET') {
    const rest = line.split('=').slice(1).join('=').trim().replace(/^["']|["']$/g, '')
    if (!rest) {
      out = `MARKETING_CAPI_ROUTE_SECRET="${randomBytes(24).toString('base64url')}"`
    }
  }
  if (key === 'NEXT_PUBLIC_GA4_MEASUREMENT_ID') {
    const ga = envValue(envContent, 'GA4_MEASUREMENT_ID')
    if (ga) out = `NEXT_PUBLIC_GA4_MEASUREMENT_ID="${ga}"`
  }
  if (key === 'NEXT_PUBLIC_GTM_CONTAINER_ID') {
    const g = envValue(envContent, 'GTM_CONTAINER_ID')
    if (g && g !== 'GTM-XXXXXXX') out = `NEXT_PUBLIC_GTM_CONTAINER_ID="${g}"`
  }
  if (key === 'NEXT_PUBLIC_META_PIXEL_ID') {
    const p = envValue(envContent, 'META_PIXEL_ID')
    if (p) out = `NEXT_PUBLIC_META_PIXEL_ID="${p}"`
  }
  linesToAdd.push(out)
  existingKeys.add(key)
}

if (linesToAdd.length > 0) {
  envContent =
    envContent.replace(/\s*$/, '\n') +
    '\n# ── Added from .env.example (keys were missing) ──\n' +
    linesToAdd.join('\n') +
    '\n'
  writeFileSync(envPath, envContent, 'utf8')
  process.stdout.write(`.env updated (+${linesToAdd.length} keys)\n`)
} else {
  process.stdout.write('.env already contains all keys from .env.example\n')
}

const localLines = [
  '# Generated by scripts/merge-env-from-example.mjs — NEXT_PUBLIC_* (local overrides)',
  '',
]
for (const line of envContent.split('\n')) {
  const k = extractKey(line)
  if (k?.startsWith('NEXT_PUBLIC_')) localLines.push(line.trim())
}
writeFileSync(localPath, localLines.join('\n') + '\n', 'utf8')
process.stdout.write(`.env.local written (${localLines.length - 2} vars)\n`)
